#!/usr/bin/env python3
"""Draw a shop-pack sheet's figure FROM ITS OWN DXF, so the two cannot disagree.

    python tools/build-sheet-figures.py

WHY THIS EXISTS. The pack's figures were hand-authored SVG, and a hand-authored
picture beside a generated cut file is a disagreement waiting to happen: when the
X carriage plate went from 154 x 407 to 170 x 430 its schedule and its DXF moved
and its picture did not, and 146 hand-placed elements with a flip base that had
itself moved could not be hand-edited safely. A sheet whose picture is subtly
wrong is worse than one with no picture at all, because it is read at the bench.

So the figure is derived from the SAME DXF the shop cuts. If the drawing is
wrong, the part is wrong too, and the error is visible rather than hidden.

WHAT IT DOES NOT DRAW. No per-hole reference callouts - P1, C1 and the rest stay
in the schedule table below the figure. Numbering them on the picture would mean
reproducing holes_for's X-cross-Y ordering here, and two implementations of one
ordering is exactly the kind of duplication this script exists to remove. The
legend gives diameter and count, which is what the picture is for; the schedule
answers which hole is which.

Each region is deleted and rebuilt, so a hand edit inside the markers is lost.
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PACK = HERE.parent / "machine" / "drawings" / "shop-pack.html"
DXF = HERE.parent / "machine" / "drawings" / "dxf"

def _load(stem, name):
    """Import a tools/ module whose filename has a hyphen in it."""
    spec = importlib.util.spec_from_file_location(name, HERE / f"{stem}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# One DXF parser and one hole reader, both borrowed rather than reimplemented.
# dxf-preview reads the geometry the shop cuts; make-dxf reads the schedule the
# geometry came from. Taking the outline and circles from the first and the REF
# LABELS from the second means the figure can only be drawn if those two agree -
# a hole the DXF has and the schedule does not stops this script dead.
parse = _load("dxf-preview", "dxfprev").parse
_mk = _load("make-dxf", "makedxf")
holes_for = _mk.holes_for

sys.path.insert(0, str(HERE))
import subst                                                     # noqa: E402

# sheet id -> the DXF it is cut from. Only sheets listed here get a generated
# figure; the rest keep their hand-authored ones until they are moved over.
SHEETS = {
    "s3a": "8-x-carriage-plate.dxf",
    "s4": "9-z-plate.dxf",
}

START = ('<!-- FIGURE:BEGIN {sheet} - generated by tools/build-sheet-figures.py '
         'from {dxf}, do not hand-edit -->')
END = "<!-- FIGURE:END {sheet} -->"

# Enough distinct hues for any one part's drill sizes, warm to cool by size.
INK = ["#b06000", "#06c", "#0a7", "#c0c", "#a00", "#555"]

PAD = 34.0          # mm of margin round the part, for labels and the legend


def fmt(v: float) -> str:
    return f"{v:g}"


def refs_for(sheet: str) -> dict:
    """{(x, y, d): 'C7'} for a sheet, read from the schedule make-dxf reads.

    The pack goes through subst first for the same reason make-dxf does: a cell
    may cite a registry symbol, and the raw file would parse '{{SYMBOL}}' as no
    coordinate at all.
    """
    src = subst.read(PACK)
    holes, _c, _e, _m = holes_for(src, sheet)
    return {(round(x, 3), round(y, 3), round(d, 3)): ref
            for x, y, d, ref in holes}


def figure(sheet: str, dxf_name: str) -> str:
    """One sheet's SVG, in the pack's own convention: svg y = height - part Y."""
    lines, circles, arcs, _texts = parse(DXF / dxf_name)
    refs = refs_for(sheet)

    # The outline layer is NOT one name. make-dxf's 'stock' kind writes OUTLINE
    # and its 'xep' kind writes STOCK, for the same thing - a border the shop
    # registers against rather than cuts. Accept both rather than pick a side.
    stock = [(a, b) for a, b, layer in lines if layer in ("STOCK", "OUTLINE")]
    if not stock:
        raise SystemExit(f"{dxf_name}: no STOCK outline to draw")

    xs = [p[0] for seg in stock for p in seg]
    ys = [p[1] for seg in stock for p in seg]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    w, h = x1 - x0, y1 - y0

    def sx(v: float) -> float:
        return v - x0

    def sy(v: float) -> float:
        return y1 - v          # flip, so part Y runs up the page

    out = [f'<svg viewBox="{-PAD:g} {-PAD:g} {w + 2 * PAD:g} {h + 2 * PAD:g}" '
           f'width="186mm" xmlns="http://www.w3.org/2000/svg">']

    out.append(f'  <!-- {sheet}: outline {fmt(w)} x {fmt(h)}, '
               f'svg y = {fmt(h)} - part Y -->')
    for (ax, ay), (bx, by) in stock:
        out.append(f'  <line x1="{sx(ax):.2f}" y1="{sy(ay):.2f}" '
                   f'x2="{sx(bx):.2f}" y2="{sy(by):.2f}" '
                   f'stroke="#111" stroke-width="1.6"/>')
    for cx, cy, r, a0, a1, layer in arcs:
        if layer not in ("STOCK", "OUTLINE"):
            continue
        out.append(f'  <circle cx="{sx(cx):.2f}" cy="{sy(cy):.2f}" r="{r:.2f}" '
                   f'fill="none" stroke="#111" stroke-width="1.0" '
                   f'stroke-dasharray="2 2"/>')

    sizes = sorted({round(d, 3) for _, _, d in circles})
    missing = []
    for cx, cy, d in circles:
        ink = INK[sizes.index(round(d, 3)) % len(INK)]
        out.append(f'  <circle cx="{sx(cx):.2f}" cy="{sy(cy):.2f}" '
                   f'r="{d / 2:.2f}" fill="none" stroke="{ink}" '
                   f'stroke-width="0.9"/>')
        ref = refs.get((round(cx, 3), round(cy, 3), round(d, 3)))
        if not ref:
            missing.append((cx, cy, d))
            continue
        # Above the hole, clear of its own circle. check-shop-pack-refs wants
        # every ref in a schedule to appear on the drawing, and it is right to:
        # a schedule that says C7 with no C7 on the picture is no use at a mill.
        out.append(f'  <text class="ref" x="{sx(cx):.2f}" '
                   f'y="{sy(cy) - d / 2 - 1.6:.2f}" fill="{ink}" '
                   f'text-anchor="middle">{ref}</text>')
    if missing:
        raise SystemExit(
            f"{dxf_name}: {len(missing)} hole(s) in the DXF that the schedule "
            f"does not name, first at {missing[0]} - the picture and the cut "
            f"file disagree, which is the whole thing this script prevents")

    # The overall size, called out on the two edges it belongs to.
    out.append(f'  <text class="dim" x="{w / 2:.1f}" y="{h + 13:.1f}" '
               f'text-anchor="middle">{fmt(w)}</text>')
    out.append(f'  <text class="dim" x="-9" y="{h / 2:.1f}" '
               f'text-anchor="middle" transform="rotate(-90 -9 {h / 2:.1f})">'
               f'{fmt(h)}</text>')

    # Legend: one row per drill size, in the same ink as the holes.
    for i, d in enumerate(sizes):
        n = sum(1 for _, _, dd in circles if round(dd, 3) == d)
        ty = -PAD + 11 + i * 9
        out.append(f'  <circle cx="4" cy="{ty - 3:.1f}" r="{d / 2:.2f}" '
                   f'fill="none" stroke="{INK[i % len(INK)]}" '
                   f'stroke-width="0.9"/>')
        out.append(f'  <text class="lbl" x="12" y="{ty:.1f}" '
                   f'fill="{INK[i % len(INK)]}">{n} &#215; &oslash;{fmt(d)}</text>')

    out.append(f'  <text class="q" x="{w:.1f}" y="{-PAD + 11:.1f}" '
               f'text-anchor="end">drawn from {dxf_name}</text>')
    out.append("</svg>")
    return "\n".join(out)


def main() -> int:
    src = PACK.read_text(encoding="utf-8")
    wrote = 0
    for sheet, dxf_name in SHEETS.items():
        start = START.format(sheet=sheet, dxf=dxf_name)
        end = END.format(sheet=sheet)
        pat = re.compile(
            re.escape(f"<!-- FIGURE:BEGIN {sheet} ") + r".*?"
            + re.escape(end), re.S)
        if not pat.search(src):
            print(f"  NO MARKERS for {sheet} - add them to the pack first")
            continue
        body = f"{start}\n{figure(sheet, dxf_name)}\n{end}"
        src = pat.sub(lambda _: body, src, count=1)
        print(f"  {sheet:5} figure from {dxf_name}")
        wrote += 1

    PACK.write_text(src, encoding="utf-8", newline="\n")
    print(f"{wrote} figure(s) rebuilt -> {PACK.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
