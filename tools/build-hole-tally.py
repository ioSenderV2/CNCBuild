#!/usr/bin/env python3
"""Rebuild the hole tally at the front of the shop pack from the sheets themselves.

Counting the drill list by hand goes stale the first time a schedule changes, and
silently - the table still looks right. So it is generated, and this script is the
only thing that writes it.

    python tools/build-hole-tally.py

It writes TWO things, and both are regenerated from the schedules every run:

  - the trip-wide tally between the TALLY markers, which sit in the pack's
    appendices - the splice is by marker, so the table moves with them;
  - a TOTAL footer row on EVERY sheet's own hole schedule, between SHEETTOTAL
    markers, giving that sheet's count per drill size and its overall hole
    count. The front tally answers "what do I order and set up"; the footer
    answers "have I drilled everything on the page in front of me", which is
    the question you have standing at the mill with one part clamped.

Both regions are deleted and rebuilt, so a hand edit to either is lost.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PACK = os.path.join(HERE, '..', 'machine', 'drawings', 'shop-pack.html')

START = '<!-- TALLY:BEGIN - generated by tools/build-hole-tally.py, do not hand-edit -->'
END = '<!-- TALLY:END -->'

# The per-sheet footer row sits INSIDE the schedule table, so its markers have
# to be legal there - an HTML comment between rows is, and it survives the
# re-parse because the whole region is stripped before anything is counted.
SROW_START = '<!-- SHEETTOTAL:BEGIN - generated, do not hand-edit -->'
SROW_END = '<!-- SHEETTOTAL:END -->'
PLATE_RE = r'<div class="plate pg-(s[0-9a-z]+)">(.*?)(?=\n<div class="plate )'
SCHED_RE = r'<table class="sched">(.*?)</table>'

# (plate div, table index) -> (sheet label, part, how many get made).
#
# THE LABEL IS NOT THE DIV. One plate div can hold several sheets: pg-s2 carries
# 2a, 2b, 2c and 2d, and calling them all "Sheet 2" sends somebody to a page
# with four parts on it.
#
# 2a AND 2b ARE THE TWO END PLATES, one each - his, and 2b's schedule is the
# whole plate, 2a's set plus the tongue's G holes. So each is drilled once and
# nothing is shared between them: the trip count is unchanged either way, but
# the attribution is now true to what gets clamped on the table.
PARTS = {
    ('s1a', 0): ('1a', 'Front Y1 riser', 1),
    ('s1b', 0): ('1b', 'Front Y2 riser', 1),
    ('s2', 0): ('2a', 'X gantry end plate, left-hand', 1),
    ('s2', 1): ('2b', 'X gantry end plate, right-hand with the tongue', 1),
    ('s2', 2): ('2c', 'Shelf bar', 2),
    ('s2', 3): ('2d', 'Nut doubler block', 3),
    ('s3a', 0): ('3a', 'X carriage plate', 1),
    ('s3b', 0): ('3b', 'Z spacer bar', 2),
    ('s3c', 0): ('3c', 'Z top stop block', 1),
    ('s3c', 1): ('3c', 'Z top stop block', 1),
    ('s4', 0): ('4', 'Z plate', 1),
    ('s5', 0): ('5', 'Nut sole plate', 3),
    ('s6', 0): ('6', 'Interposer', 3),
    ('s7', 0): ('7', 'Rear plate', 1),
    ('s8', 0): ('8', 'Front joining strip', 3),
    ('s9', 0): ('9', 'Outboard plate', 2),
    ('s10', 0): ('10', 'X back joining plate', 1),
    # No s11: Sheet 11 is an installation page, not a part. All three sole
    # plates are Sheet 5's one drawing, so its copies carry the X one too.
}

# What each diameter is FOR. Keyed by diameter; the pack has one job per size.
PURPOSE = {
    '4.2': 'Pilot for M5 &mdash; <b>drilled through</b> &middot; see the tap appendix',
    '5.2': 'M5 clearance, <b>counterbore pilot</b> &mdash; stays 5.2 on 2a and 3a',
    '6': 'M5 clearance, <b>one size throughout</b> &middot; plus the three &oslash;6 hex-driver access holes',
    '6.8': 'Pilot for M8 &mdash; <b>drilled through</b> &middot; see the tap appendix',
    '8.4': 'M8 <b>close fit</b> &mdash; the shelf bar only, where the roll shim bears and float is <b>not</b> wanted',
    '9': 'M8 clearance &mdash; into extrusion T-nuts and beam corner bores, <b>float is wanted</b>',
    '22': 'The Z screw passes through the top stop block',
    '35': 'Encoder sensor bore',
}


def text_of(html):
    t = re.sub(r'<[^>]+>', '', html)
    t = re.sub(r'&#(\d+);', lambda m: chr(int(m.group(1))), t)
    for ent, ch in (('&ndash;', '-'), ('&mdash;', '-'), ('&nbsp;', ' '),
                    ('&times;', '*'), ('&oslash;', 'o'), ('&plusmn;', '+-')):
        t = t.replace(ent, ch)
    return ' '.join(t.split())


def dia_key(d):
    try:
        return (0, float(d))
    except ValueError:
        return (1, d)


def collect(src):
    # `tables` carries what each schedule lists on its own, which is NOT the
    # same as what it contributes to the trip: sheet 2's second table repeats
    # the first one's refs, and those are counted once for the trip but are
    # really drilled on the page they are drawn on. The footer shows the
    # table's own holes and says how many of them repeat.
    per_part, trip, unknown, tables = {}, {}, [], []
    for name, blk in re.findall(PLATE_RE, src, re.S):
        for ti, t in enumerate(re.findall(SCHED_RE, blk, re.S)):
            hdr = [text_of(x) for x in re.findall(r'<th[^>]*>(.*?)</th>', t, re.S)]
            dcol = hdr.index('o') if 'o' in hdr else None
            # BY HEADER NAME, not by position - the same contract make-dxf.py
            # reads these tables under. Qty was hardcoded at index 2, which
            # held only while every schedule carried the same columns in the
            # same order.
            qcol = next((i for i, h in enumerate(hdr)
                         if h.split()[:1] == ['Qty']), 2)
            label, part, made = PARTS.get((name, ti), (None, None, 1))
            if part is None:
                unknown.append('%s table %d' % (name, ti))
                continue
            # NOTHING IS SHARED BETWEEN SCHEDULES ANY MORE. 2b used to be read
            # as 2a's plate drawn complete, so its repeated refs were counted
            # once; it is its own plate now and drills its own full set.
            skip = set()
            # `own` is every hole the table lists; `contrib` is what it adds to
            # the trip, which differs where a table repeats refs from another.
            own, contrib, cutouts, repeated = {}, {}, 0, 0
            for r in re.findall(r'<tr[^>]*>(.*?)</tr>', t, re.S):
                if '<th' in r:
                    continue
                c = [text_of(x) for x in re.findall(r'<td[^>]*>(.*?)</td>', r, re.S)]
                if len(c) < 4 or dcol is None or len(c) <= dcol:
                    continue
                m = re.search(r'\d+', c[qcol].replace('4 * 7', '28'))
                n = int(m.group()) if m else 1
                dia = c[dcol].strip()
                if not re.match(r'^\d+(\.\d+)?$', dia):
                    cutouts += n  # the riser windows are cut-outs, not a drill size
                    continue
                own[dia] = own.get(dia, 0) + n
                if c[0] in skip:
                    repeated += n
                    continue
                per_part[dia] = per_part.get(dia, 0) + n
                trip[dia] = trip.get(dia, 0) + n * made
                contrib[dia] = contrib.get(dia, 0) + n
            tables.append(dict(sheet=name, ti=ti, label=label, part=part,
                               made=made, own=own, contrib=contrib,
                               cutouts=cutouts, repeated=repeated,
                               cols=len(hdr)))
    return per_part, trip, unknown, tables


def by_size(tables):
    """dia -> [(sheet, part, per-part count, copies)], in sheet order.

    The trip figure for a sheet is its own count TIMES the copies made, which
    is the thing worth printing beside the drill: set the size up once and this
    is how many go through it on that part.
    """
    out = {}
    for t in tables:
        for dia, n in t['contrib'].items():
            out.setdefault(dia, []).append(
                (t['label'], t['part'], n, t['made']))
    return out


def strip_sheet_totals(src):
    """Remove every generated footer region, so nothing is counted twice."""
    return re.sub(re.escape(SROW_START) + r'.*?' + re.escape(SROW_END) + r'\s*',
                  '', src, flags=re.S)


def sheet_total_row(t, nl):
    """The TOTAL footer for ONE schedule: per drill size, then the sheet's own total.

    It goes in the Qty column, because that column already means "how many
    holes" on every other row of the table - a total in a different column is
    a number the eye has to be told how to read.
    """
    sizes = ' &middot; '.join('%d &times; &oslash;%s' % (t['own'][d], d)
                              for d in sorted(t['own'], key=dia_key))
    n = sum(t['own'].values())
    tail = []
    if t['cutouts']:
        tail.append('plus %d cut-out%s, not counted as holes'
                    % (t['cutouts'], '' if t['cutouts'] == 1 else 's'))
    if t['repeated']:
        tail.append('%d of these repeat the schedule above and are counted '
                    'once in the trip tally' % t['repeated'])
    if t['made'] > 1:
        tail.append('%d of this part get made &mdash; <b>%d holes</b> in all'
                    % (t['made'], n * t['made']))
    note = ' &mdash; '.join(tail) if tail else 'holes in this one part'
    span = max(1, t['cols'] - 3)
    return nl.join([
        SROW_START,
        '<tr class="tot"><td><b>TOTAL</b></td><td>%s</td><td><b>%d</b></td>'
        '<td colspan="%d" class="tn">%s</td></tr>' % (sizes or '&mdash;', n,
                                                     span, note),
        SROW_END])


def insert_sheet_totals(src, tables, nl):
    """Splice one footer into each schedule, working back to front by offset."""
    byref = {(t['sheet'], t['ti']): t for t in tables}
    cuts = []
    for pm in re.finditer(PLATE_RE, src, re.S):
        base = pm.start(2)
        for ti, tm in enumerate(re.finditer(SCHED_RE, pm.group(2), re.S)):
            t = byref.get((pm.group(1), ti))
            if t is None or not t['own']:
                continue      # no mapped part, or nothing drilled - no footer
            cuts.append((base + tm.end(1), sheet_total_row(t, nl)))
    for at, row in sorted(cuts, reverse=True):
        src = src[:at] + row + nl + src[at:]
    return src, len(cuts)


def render(per_part, trip, sized):
    """One block per drill size, listing the sheets that use it.

    Set a size up once and work every sheet under it. Where a part is made more
    than once the qty is its sheet count times the copies, and the sum is shown
    so the figure can be checked against the sheet without arithmetic.
    """
    key = dia_key
    out = [START,
           '<h2 id="drills">Appendix &mdash; what gets drilled, by drill size</h2>',
           '<p style="margin:0 0 .4rem;font-size:9.5pt"><b>Generated from the hole '
           'schedules</b> by tools/build-hole-tally.py, so it cannot drift from them. '
           '<b>Qty is for the trip</b>: the sheet\'s own count times the number of that '
           'part made, and where that is more than one the sum is shown.</p>',
           '<table class="sched">',
           '<tr><th>&oslash;</th><th>Sheet</th><th class="d">Qty</th>'
           '<th>What it is for</th></tr>']
    tt = 0
    for d in sorted(per_part, key=key):
        rows = sorted(sized.get(d, []), key=lambda r: sheet_key(r[0]))
        why = PURPOSE.get(d, '&#9888; <b>not described</b> &mdash; add it to '
                             'tools/build-hole-tally.py')
        span = max(1, len(rows))
        for i, (sheet, part, n, made) in enumerate(rows):
            qty = n * made
            tt += qty
            cell = ('%d <span class="tn">(%d&times;%d)</span>' % (qty, made, n)
                    if made > 1 else '%d' % qty)
            cells = []
            if i == 0:
                cells.append('<td rowspan="%d"><b>&oslash;%s</b><br>'
                             '<span class="tn">%d in all</span></td>'
                             % (span, d, trip[d]))
            cells.append('<td>%s <span class="tn">&mdash; %s</span></td>'
                         % (sheet_label(sheet), part))
            cells.append('<td class="d">%s</td>' % cell)
            if i == 0:
                cells.append('<td rowspan="%d">%s</td>' % (span, why))
            out.append('<tr>%s</tr>' % ''.join(cells))
    out.append('<tr><td colspan="2"><b>TOTAL ON THE TRIP</b></td>'
               '<td class="d"><b>%d</b></td>'
               '<td>Cut-outs are not holes and are not counted</td></tr>' % tt)
    out.append('</table>')
    out.append(END)
    return '\n'.join(out)


def sheet_key(s):
    """Sort 1a, 2, 10 the way a human reads them, not asciibetically."""
    m = re.match(r'(\d+)([a-z]*)', s)
    return (int(m.group(1)), m.group(2)) if m else (99, s)


def sheet_label(s):
    return 'Sheet ' + s


def main():
    src = io.open(PACK, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in src else '\n'
    src = strip_sheet_totals(src)
    per_part, trip, unknown, tables = collect(src)
    if unknown:
        print('schedules with no part mapping, NOT counted: %s' % ', '.join(unknown))
        return 1
    src, nfoot = insert_sheet_totals(src, tables, nl)
    table = render(per_part, trip, by_size(tables)).replace('\n', nl)

    if START in src and END in src:
        lo = src.index(START)
        hi = src.index(END) + len(END)
        src = src[:lo] + table + src[hi:]
    else:
        anchor = '<p style="margin:0 0 .35rem"><b>Sheets that exist and are drawable</b>'
        if anchor not in src:
            print('cannot find where to put the tally')
            return 1
        src = src.replace(anchor, table + nl + nl + anchor, 1)
    io.open(PACK, 'w', encoding='utf-8', newline='').write(src)

    print('%d sizes, %d holes across the schedules, %d on the trip'
          % (len(per_part), sum(per_part.values()), sum(trip.values())))
    print('%d sheet schedules carry a TOTAL footer' % nfoot)
    for t in tables:
        if not t['own']:
            print('  no holes counted on %s table %d (%s)'
                  % (t['sheet'], t['ti'], t['part']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
